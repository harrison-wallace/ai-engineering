#!/usr/bin/env python3
"""List the code comments in scope, or delete chosen ones.

Usage:
  comments.py list [diff | repo | <path>...]   (default: diff)
  comments.py delete <loc>... | -              (- reads locs from stdin, one per line)

`list` prints TSV, one comment block per row: loc<TAB>kind<TAB>tag<TAB>text
  loc   path:line or path:start-end, relative to the repo root, plus :col for a comment
        that shares its line with code (path:12:30)
  kind  line (full-line comments, adjacent lines grouped), trailing (after code on the
        same line), block (/* */ or <!-- -->), doc (/** */, ///, //!)
  tag   todo (TODO, FIXME, HACK, XXX, workaround, temporary, for now), code (looks like
        commented-out code), or -
  text  the comment with its markers stripped, lines joined by " | ", cut at 200 chars
A summary goes to stderr. Directives (eslint-disable, @ts-*, noqa, //go:, shellcheck, ...),
shebangs, modelines, license headers, and generated or vendored files are never listed.

`delete` removes the blocks at the given locs, taken from a `list` run on the unchanged
files. Pass every loc in one call: it deletes bottom-up, so line numbers stay valid. A loc
that no longer matches a comment is reported on stderr and skipped (exit 2).
The scan is line-based and ignores quoted strings. It is a lead list, not a parser.
"""
import os
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

C_LIKE = {"js", "mjs", "cjs", "jsx", "ts", "mts", "cts", "tsx", "go", "rs", "java", "kt", "kts",
          "c", "h", "cc", "cpp", "cxx", "hpp", "cs", "swift", "scala", "dart", "php", "groovy",
          "proto", "jsonc", "gradle"}
HASH = {"py", "pyi", "sh", "bash", "zsh", "fish", "rb", "pl", "r", "yaml", "yml", "toml", "nix",
        "ex", "exs", "ps1", "cfg", "conf", "mk", "cmake", "tf", "tfvars", "hcl", "jl", "cr"}
DASH = {"sql", "lua", "hs", "elm"}
STYLE = {"css", "scss", "sass", "less"}
MARKUP = {"html", "htm", "xml", "svg", "vue", "svelte", "astro"}
NAMED = {"dockerfile": "py", "makefile": "py", "justfile": "py", "jenkinsfile": "groovy",
         "vagrantfile": "rb", "gemfile": "rb", "rakefile": "rb"}

SKIP_DIRS = {"node_modules", "vendor", "third_party", "third-party", "dist", "build", "out",
             ".next", ".nuxt", ".svelte-kit", "coverage", "archive", "__pycache__", ".git",
             ".venv", "venv", "target", "generated", "__generated__", ".terraform"}
SKIP_FILE = re.compile(r"(\.min\.|\.lock$|\.d\.ts$|_pb2\.pyi?$|\.pb\.go$|\.gen\.|\.generated\.|"
                       r"-lock\.ya?ml$|package-lock\.json$)")
GENERATED = re.compile(r"@generated|DO NOT EDIT|auto-?generated|generated by", re.I)
DIRECTIVE = re.compile(
    r"^\s*(eslint|@ts-|prettier-ignore|biome-ignore|istanbul ignore|c8 ignore|v8 ignore|noqa|"
    r"type:\s*ignore|pyright:|mypy:|pylint:|ruff:|nolint|NOLINT|go:|\+build|shellcheck|rubocop:|"
    r"NOSONAR|nosec|tslint:|jshint|jscs:|global |@jsx|@flow|#?region|#?endregion|<reference|"
    r"@license|@preserve|@generated|clang-format|pragma|fmt:|isort:|tflint-ignore|checkov:|"
    r"tfsec:|trivy:|kics|hadolint|yamllint|markdownlint|cspell|spell-checker|webpack[A-Z]|"
    r"@vite-ignore|swiftlint|syntax=|escape=|language=|-\*-|vim?:|ex:|coding[:=]|"
    r"SPDX-|svelte-ignore|@vue-ignore|eslint-disable|stylelint|@refresh|deno-|"
    r"@(jest|vitest)-environment)", re.I)
LICENSE = re.compile(r"copyright|licen[cs]e|SPDX", re.I)
TODO = re.compile(r"\b(TODO|FIXME|HACK|XXX|KLUDGE|workaround|temporar(y|ily)|for now|quick fix|"
                  r"hacky|band-?aid)\b", re.I)
CODE = re.compile(r"(^(import|from|export|const|let|var|def|class|func|fn|return|if|for|while|"
                  r"print|console\.|await|async|self\.|this\.)\b.*[(){};=:]|[;{}]\s*$|"
                  r"^\w+(\.\w+)*\(.*\)\s*;?$|^\w+\s*=\s*\S)")


def lang_of(path: Path):
    name = path.name.lower()
    if name in NAMED:
        return NAMED[name]
    if name.startswith("dockerfile") or name.endswith(".dockerfile"):
        return "py"
    ext = path.suffix.lower().lstrip(".")
    for group in (C_LIKE, HASH, DASH, STYLE, MARKUP):
        if ext in group:
            return ext
    return None


def syntax(lang):
    """(line tokens, block pairs, quote chars, multi-line quote chars)."""
    if lang in C_LIKE or lang in {"tf", "tfvars", "hcl"}:
        line = ["//"] + (["#"] if lang in {"tf", "tfvars", "hcl", "php"} else [])
        quotes = '"`' if lang in {"rs", "go"} else '"\'`'
        if lang == "rs":
            quotes = '"'
        return line, [("/*", "*/")], quotes, "`"
    if lang in HASH:
        triple = lang in {"py", "pyi"}
        return ["#"], [], "\"'", ('"""', "'''") if triple else ()
    if lang in DASH:
        return ["--"], [("/*", "*/")] if lang == "sql" else [], "'\"", ()
    if lang in STYLE:
        return (["//"] if lang in {"scss", "less", "sass"} else []), [("/*", "*/")], "\"'", ()
    if lang in MARKUP:
        return ["//"], [("<!--", "-->"), ("/*", "*/")], "\"'`", "`"
    return [], [], "", ()


def scan(text: str, lang: str):
    """Yield raw comments: dict(start, end, scol, ecol, kind, body, full)."""
    line_toks, blocks, quotes, multi = syntax(lang)
    lines = text.split("\n")
    out = []
    in_block = None  # (closer, start_line, start_col, body_parts, opener)
    in_str = None    # multi-line string delimiter
    for i, raw in enumerate(lines):
        j = 0
        n = len(raw)
        code_before = False
        if in_block:
            closer = in_block[0]
            k = raw.find(closer)
            if k < 0:
                in_block[3].append(raw)
                continue
            in_block[3].append(raw[:k])
            _, sl, sc, parts, opener = in_block
            end_col = k + len(closer)
            out.append(dict(start=sl, end=i, scol=sc, ecol=end_col, opener=opener,
                            body=parts, lead=in_block_lead(lines[sl], sc),
                            tail=raw[end_col:].strip() != ""))
            in_block = None
            j = end_col
            code_before = True
        while j < n:
            if in_str:
                k = raw.find(in_str, j)
                if k < 0:
                    j = n
                    break
                j = k + len(in_str)
                in_str = None
                code_before = True
                continue
            ch = raw[j]
            if multi and isinstance(multi, tuple) and raw.startswith(multi, j):
                delim = raw[j:j + 3]
                k = raw.find(delim, j + 3)
                if k < 0:
                    in_str = delim
                    j = n
                    break
                j = k + 3
                code_before = True
                continue
            if ch in quotes:
                k = j + 1
                while k < n and raw[k] != ch:
                    k += 2 if raw[k] == "\\" else 1
                if k >= n and isinstance(multi, str) and ch in multi:
                    in_str = ch
                    j = n
                    break
                j = k + 1
                code_before = True
                continue
            hit = None
            for opener, closer in blocks:
                if raw.startswith(opener, j):
                    hit = ("block", opener, closer)
                    break
            if not hit:
                for tok in line_toks:
                    if raw.startswith(tok, j) and (tok != "#" or j == 0 or raw[j - 1].isspace()):
                        if tok == "//" and j > 0 and raw[j - 1] == ":":
                            continue  # a bare URL such as http://
                        hit = ("line", tok, None)
                        break
            if hit and hit[0] == "line":
                out.append(dict(start=i, end=i, scol=j, ecol=n, opener=hit[1],
                                body=[raw[j + len(hit[1]):]], lead=code_before or
                                raw[:j].strip() != "", tail=False))
                j = n
                break
            if hit:
                opener, closer = hit[1], hit[2]
                k = raw.find(closer, j + len(opener))
                if k < 0:
                    in_block = [closer, i, j, [raw[j + len(opener):]], opener]
                    j = n
                    break
                end_col = k + len(closer)
                out.append(dict(start=i, end=i, scol=j, ecol=end_col, opener=opener,
                                body=[raw[j + len(opener):k]],
                                lead=code_before or raw[:j].strip() != "",
                                tail=raw[end_col:].strip() != ""))
                j = end_col
                code_before = True
                continue
            if not ch.isspace():
                code_before = True
            j += 1
    return out


def in_block_lead(first_line: str, scol: int) -> bool:
    return first_line[:scol].strip() != ""


def clean(body):
    rows = []
    for part in body:
        s = part.strip()
        s = re.sub(r"^(\*+|/+|!|#+|-+)\s?", "", s).strip()
        s = re.sub(r"\*+/?$", "", s).strip()
        if s:
            rows.append(s)
    return rows


def group(raw, lines):
    """Merge adjacent full-line comments with the same opener into one block."""
    blocks = []
    for c in raw:
        full = not c["lead"] and not c["tail"]
        c["full"] = full
        c["directive"] = is_directive(c["body"][0] if c["body"] else "")
        prev = blocks[-1] if blocks else None
        if (prev and full and prev["full"] and c["opener"] == prev["opener"]
                and not c["directive"] and not prev["directive"]
                and c["opener"] not in ("/*", "<!--") and c["start"] == prev["end"] + 1):
            prev["end"] = c["end"]
            prev["body"] += c["body"]
            prev["ecol"] = c["ecol"]
            continue
        blocks.append(dict(c))
    for b in blocks:
        first = b["body"][0] if b["body"] else ""
        if b["opener"] in ("/*", "<!--"):
            b["kind"] = "doc" if lines[b["start"]][b["scol"]:].startswith("/**") else "block"
        elif b["opener"] == "//" and (first.startswith("/") or first.startswith("!")):
            b["kind"] = "doc"
        else:
            b["kind"] = "line"
        if not b["full"]:
            b["kind"] = "trailing"
        b["rows"] = clean(b["body"])
    return blocks


def is_directive(raw: str) -> bool:
    cleaned = clean([raw])
    return bool(DIRECTIVE.match(raw) or (cleaned and DIRECTIVE.match(cleaned[0])))


def skip(b, lines):
    rows = b["rows"]
    if not rows:
        return True
    if b["start"] == 0 and lines[0].startswith("#!"):
        return True
    if b["directive"]:
        return True
    if b["start"] < 40 and LICENSE.search(" ".join(rows)) and b["kind"] != "trailing":
        return True
    return False


def comments_in(path: Path, rel: str):
    lang = lang_of(path)
    if not lang:
        return None, []
    try:
        if path.stat().st_size > 1_000_000:
            return None, []
        with open(path, encoding="utf-8", newline="") as f:
            raw = f.read()
    except (OSError, UnicodeDecodeError):
        return None, []
    crlf = "\r\n" in raw
    text = raw.replace("\r\n", "\n") if crlf else raw
    lines = text.split("\n")
    if GENERATED.search("\n".join(lines[:5])):
        return None, []
    found = []
    skipped = 0
    for b in group(scan(text, lang), lines):
        if skip(b, lines):
            skipped += 1
            continue
        found.append(b)
    return (text, skipped, crlf), found


def git(*args, root="."):
    r = subprocess.run(["git", "-c", "core.quotePath=false", *args], cwd=root, capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else ""


def paths(*args, root="."):
    return [p for p in git(*args, root=root).split("\0") if p]


def wanted(rel: str) -> bool:
    parts = rel.split("/")
    if any(p in SKIP_DIRS for p in parts[:-1]):
        return False
    if SKIP_FILE.search(parts[-1]):
        return False
    if "/fix-comments/" in "/" + rel:  # this skill quotes comments on purpose
        return False
    return lang_of(Path(rel)) is not None


def changed_lines(root):
    ranges = defaultdict(list)
    cur = None
    diff = git("diff", "HEAD", "-U0", "--no-color", "--no-ext-diff", "--src-prefix=a/",
               "--dst-prefix=b/", root=root)
    if not diff and not git("rev-parse", "--verify", "HEAD", root=root):
        return None  # no commits yet: treat every file as new
    for line in diff.splitlines():
        if line.startswith("+++ "):
            cur = line[6:].rstrip("\t") if line.startswith("+++ b/") else None
        elif line.startswith("@@") and cur:
            m = re.search(r"\+(\d+)(?:,(\d+))?", line)
            start, count = int(m.group(1)), int(m.group(2) or 1)
            if count:
                ranges[cur].append((start - 1, start - 2 + count))
    return ranges


def select(root, target):
    """Return {rel: None (all lines) or [(lo, hi)] zero-based inclusive}."""
    untracked = paths("ls-files", "-z", "--others", "--exclude-standard", root=root)
    if target == ["diff"]:
        ranges = changed_lines(root)
        if ranges is None:
            return {f: None for f in paths("ls-files", "-z", root=root) + untracked if wanted(f)}
        files = {f: r for f, r in ranges.items() if wanted(f)}
        files.update({f: None for f in untracked if wanted(f)})
        return files
    if target == ["repo"]:
        return {f: None for f in paths("ls-files", "-z", root=root) + untracked if wanted(f)}
    files = {}
    for p in target:
        rel = os.path.relpath(os.path.abspath(p), root)
        listed = paths("ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", rel,
                       root=root)
        if not listed and os.path.isfile(os.path.join(root, rel)):
            listed = [rel]
        if not listed and os.path.isdir(os.path.join(root, rel)):
            for d, dirs, names in os.walk(os.path.join(root, rel)):
                dirs[:] = [x for x in dirs if x not in SKIP_DIRS]
                listed += [os.path.relpath(os.path.join(d, x), root) for x in names]
        files.update({f: None for f in listed if wanted(f)})
    return files


def loc(rel, b):
    s, e = b["start"] + 1, b["end"] + 1
    span = f"{s}" if s == e else f"{s}-{e}"
    return f"{rel}:{span}" if b["full"] else f"{rel}:{span}:{b['scol'] + 1}"


LOC = re.compile(r"^(.*?):(\d+(?:-\d+)?(?::\d+)?)$")


def cmd_list(root, target):
    files = select(root, target or ["diff"])
    total = skipped = nfiles = 0
    for rel in sorted(files):
        meta, found = comments_in(Path(root) / rel, rel)
        if meta is None:
            continue
        skipped += meta[1]
        keep = files[rel]
        hit = False
        for b in found:
            if keep is not None and not any(lo <= b["end"] and b["start"] <= hi for lo, hi in keep):
                continue
            joined = " | ".join(b["rows"])
            tag = "todo" if TODO.search(joined) else ("code" if any(CODE.search(r) for r in b["rows"])
                                                      else "-")
            text = joined if len(joined) <= 200 else joined[:197] + "..."
            print(f"{loc(rel, b)}\t{b['kind']}\t{tag}\t{text}")
            total += 1
            hit = True
        nfiles += hit
    scope = " ".join(target or ["diff"])
    print(f"comments: {total} in {nfiles} files ({scope}); skipped {skipped} directives, "
          f"shebangs, and license headers", file=sys.stderr)


def cmd_delete(root, locs):
    if locs == ["-"]:
        locs = [x.strip() for x in sys.stdin if x.strip()]
    by_file = defaultdict(set)
    missing = deleted = touched = 0
    for item in locs:
        m = LOC.match(item.split("\t")[0].strip())
        if not m:
            print(f"bad loc: {item}", file=sys.stderr)
            missing += 1
            continue
        by_file[m.group(1)].add(m.group(2))
    for rel, spans in sorted(by_file.items()):
        path = Path(root) / rel
        meta, found = comments_in(path, rel)
        if meta is None:
            print(f"not found: {rel}", file=sys.stderr)
            missing += len(spans)
            continue
        index = {LOC.match(loc(rel, b)).group(2): b for b in found}
        targets = []
        for span in spans:
            if span in index:
                targets.append(index[span])
            else:
                print(f"not found: {rel}:{span}", file=sys.stderr)
                missing += 1
        if not targets:
            continue
        lines = meta[0].split("\n")
        for b in sorted(targets, key=lambda b: (b["start"], b["scol"]), reverse=True):
            cut(lines, b)
            deleted += 1
        touched += 1
        content = "\n".join(lines)
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(content.replace("\n", "\r\n") if meta[2] else content)
    print(f"deleted {deleted} comments in {touched} files", file=sys.stderr)
    return 2 if missing else 0


def cut(lines, b):
    s, e = b["start"], b["end"]
    if b["full"]:
        del lines[s:e + 1]
        # Do not leave two blank lines, or a blank line at the top of the file.
        if s < len(lines) and not lines[s].strip() and (s == 0 or not lines[s - 1].strip()):
            del lines[s]
        return
    head = lines[s][:b["scol"]]
    rest = lines[e][b["ecol"]:]
    left, right = head.rstrip(), rest.lstrip()
    if not head.strip():
        joined = head + right
    elif not right or right[0] in ",;:)]}>" or left[-1] in "([{<":
        joined = left + right
    else:
        joined = left + " " + right
    lines[s:e + 1] = [joined.rstrip()] if joined.strip() else []


def main(argv):
    if not argv or argv[0] not in ("list", "delete"):
        print(__doc__, file=sys.stderr)
        return 1
    root = git("rev-parse", "--show-toplevel").strip() or os.getcwd()
    if argv[0] == "list":
        cmd_list(root, argv[1:])
        return 0
    if len(argv) < 2:
        print("delete: give locs, or - to read them from stdin", file=sys.stderr)
        return 1
    return cmd_delete(root, argv[1:])


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
